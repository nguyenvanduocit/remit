//! The TypeScript text of lowered declarations and contracts.

use std::collections::BTreeSet;

use crate::lower::{Body, Call, Case, Contract, Data, Decl, Field, Object, Repr, Ty};
use crate::rename::Rule;

/// A line a union of strings is folded at.
const WIDTH: usize = 120;

fn header(krate: &str, file: &str) -> String {
    format!("// Generated by tsgen from the {krate} crate's {file}: do not edit; `make gen` writes it again.\n")
}

/// `types.generated.ts`: one declaration per type and constant.
pub fn types(krate: &str, file: &str, decls: &[Decl]) -> String {
    let mut out = header(krate, file);
    for d in decls {
        out.push('\n');
        out.push_str(&decl(d));
    }
    out
}

fn decl(d: &Decl) -> String {
    let mut docs = d.docs.clone();
    let text = match &d.body {
        Body::Const(literal) => format!("export const {} = {literal};\n", d.name),
        Body::Alias(ty) => format!("export type {} = {};\n", d.name, render(ty)),
        Body::Object(object) => format!("export type {} = {};\n", d.name, intersection(object, "")),
        Body::Strings(cases) => {
            for c in cases.iter().filter(|c| !c.docs.is_empty()) {
                let name = if c.name.is_empty() { quote("") } else { c.name.clone() };
                docs.push(format!("- `{name}`: {}", c.docs.join(" ")));
            }
            let names: Vec<String> = cases.iter().map(|c| quote(&c.name)).collect();
            let line = format!("export type {} = {};\n", d.name, names.join(" | "));
            if line.len() <= WIDTH {
                line
            } else {
                let mut folded = format!("export type {} =\n", d.name);
                for n in &names {
                    folded.push_str(&format!("  | {n}\n"));
                }
                fold_end(folded)
            }
        }
        Body::Union(repr, cases) => {
            let mut text = format!("export type {} =\n", d.name);
            for c in cases {
                text.push_str(&comment(&c.docs, "  "));
                text.push_str(&format!("  | {}\n", case(repr, c)));
            }
            fold_end(text)
        }
    };
    format!("{}{text}", comment(&docs, ""))
}

/// Ends a folded declaration with its `;`.
fn fold_end(mut text: String) -> String {
    if text.ends_with('\n') {
        text.pop();
    }
    text.push_str(";\n");
    text
}

fn case(repr: &Repr, c: &Case) -> String {
    let indent = "    ";
    match (repr, &c.data) {
        (Repr::Untagged, Data::Unit) => "null".to_owned(),
        (Repr::Untagged, Data::Newtype(ty)) => render(ty),
        (Repr::Untagged, Data::Struct(o)) => intersection(o, indent),
        (Repr::Internal { tag }, Data::Unit) => format!("{{ {}: {} }}", key(tag), quote(&c.name)),
        (Repr::Internal { tag }, Data::Newtype(ty)) => {
            format!("({{ {}: {} }} & {})", key(tag), quote(&c.name), render(ty))
        }
        (Repr::Internal { tag }, Data::Struct(o)) => {
            intersection_with(o, indent, &[format!("{}: {};", key(tag), quote(&c.name))])
        }
        (Repr::Adjacent { tag, .. }, Data::Unit) => format!("{{ {}: {} }}", key(tag), quote(&c.name)),
        (Repr::Adjacent { tag, content }, Data::Newtype(ty)) => {
            format!(
                "{{ {}: {}; {}: {} }}",
                key(tag),
                quote(&c.name),
                key(content),
                render(ty)
            )
        }
        (Repr::Paired { tag, content }, Data::Unit) => {
            format!("{{ {}: {}; {}: '' }}", key(tag), quote(&c.name), key(content))
        }
        (Repr::Paired { tag, content }, Data::Newtype(ty)) => {
            format!(
                "{{ {}: {}; {}: {} }}",
                key(tag),
                quote(&c.name),
                key(content),
                render(ty)
            )
        }
        (Repr::Paired { .. }, Data::Struct(o)) => intersection(o, indent),
        (Repr::Adjacent { tag, content }, Data::Struct(o)) => {
            let lead = [
                format!("{}: {};", key(tag), quote(&c.name)),
                format!("{}: {};", key(content), intersection(o, "      ")),
            ];
            object(&[], indent, &lead)
        }
    }
}

fn intersection(o: &Object, indent: &str) -> String {
    intersection_with(o, indent, &[])
}

/// An object and the types it flattens; `lead` are lines written before the fields (a variant's tag).
fn intersection_with(o: &Object, indent: &str, lead: &[String]) -> String {
    let mut parts = Vec::new();
    if !o.fields.is_empty() || o.flatten.is_empty() || !lead.is_empty() {
        parts.push(object(&o.fields, indent, lead));
    }
    parts.extend(o.flatten.iter().map(render));
    parts.join(" & ")
}

fn object(fields: &[Field], indent: &str, lead: &[String]) -> String {
    if fields.is_empty() && lead.is_empty() {
        return "{}".to_owned();
    }
    let inner = format!("{indent}  ");
    let mut text = "{\n".to_owned();
    for line in lead {
        text.push_str(&format!("{inner}{line}\n"));
    }
    for f in fields {
        text.push_str(&comment(&f.docs, &inner));
        let mark = if f.optional { "?" } else { "" };
        text.push_str(&format!("{inner}{}{mark}: {};\n", key(&f.name), render(&f.ty)));
    }
    text.push_str(indent);
    text.push('}');
    text
}

fn render(ty: &Ty) -> String {
    match ty {
        Ty::String => "string".to_owned(),
        Ty::Number => "number".to_owned(),
        Ty::Boolean => "boolean".to_owned(),
        Ty::Unknown => "unknown".to_owned(),
        Ty::Named(name, _) => name.clone(),
        Ty::Array(inner) => match **inner {
            Ty::Nullable(_) => format!("({})[]", render(inner)),
            _ => format!("{}[]", render(inner)),
        },
        Ty::Nullable(inner) => format!("{} | null", render(inner)),
        Ty::Record(inner) => format!("Record<string, {}>", render(inner)),
    }
}

/// `api.generated.ts`: for each contract, what each call takes and answers by its name on the wire, the `Send` the core
/// implements, one async function per call over it, and what each push carries.
pub fn api(krate: &str, file: &str, contracts: &[(String, &Contract)]) -> String {
    let mut out = header(krate, file);
    let mut names = BTreeSet::new();
    for (_, c) in contracts {
        for call in c.calls.iter().chain(&c.pushes) {
            for ty in call.args.iter().map(|a| &a.ty).chain(&call.answer) {
                named(ty, &mut names);
            }
        }
    }
    if !names.is_empty() {
        let list: Vec<&str> = names.iter().map(String::as_str).collect();
        out.push_str(&format!(
            "\nimport type {{ {} }} from './types.generated';\n",
            list.join(", ")
        ));
    }
    for (prefix, c) in contracts {
        if !c.calls.is_empty() {
            out.push_str(&calls(prefix, &c.calls));
        }
        if !c.pushes.is_empty() {
            out.push_str(&format!(
                "\n/** What each push carries, by its name on the wire. */\nexport interface {prefix}PushArgs {{\n"
            ));
            for p in &c.pushes {
                out.push_str(&comment(&p.docs, "  "));
                out.push_str(&format!("  {}: {};\n", p.method, args_type(p)));
            }
            out.push_str("}\n");
        }
    }
    out
}

fn calls(prefix: &str, calls: &[Call]) -> String {
    let mut out =
        format!("\n/** What each call takes, by its name on the wire. */\nexport interface {prefix}CallArgs {{\n");
    for c in calls {
        out.push_str(&format!("  {}: {};\n", c.method, args_type(c)));
    }
    out.push_str(&format!(
        "}}\n\n/** What each call answers. */\nexport interface {prefix}CallAnswers {{\n"
    ));
    for c in calls {
        let answer = c.answer.as_ref().map_or_else(|| "void".to_owned(), render);
        out.push_str(&format!("  {}: {answer};\n", c.method));
    }
    out.push_str(&format!(
        "}}\n\n/** Sends one call and settles with its answer, or fails with the call's error; the core adds a changing call's `Request`. */\n\
         export type {prefix}Send = <M extends keyof {prefix}CallArgs>(method: M, args: {prefix}CallArgs[M]) => Promise<{prefix}CallAnswers[M]>;\n\n\
         /** One async function per call. */\n\
         export function create{prefix}Api(send: {prefix}Send) {{\n  return {{\n"
    ));
    for c in calls {
        let params: Vec<String> = c
            .args
            .iter()
            .map(|a| format!("{}: {}", a.name, render(&a.ty)))
            .collect();
        let names: Vec<&str> = c.args.iter().map(|a| a.name.as_str()).collect();
        let body = if names.is_empty() {
            "{}".to_owned()
        } else {
            format!("{{ {} }}", names.join(", "))
        };
        let answer = c.answer.as_ref().map_or_else(|| "void".to_owned(), render);
        out.push_str(&comment(&c.docs, "    "));
        out.push_str(&format!(
            "    {}: ({}): Promise<{answer}> => send({}, {body}),\n",
            Rule::Camel.field(&c.method),
            params.join(", "),
            quote(&c.method),
        ));
    }
    out.push_str(&format!(
        "  }};\n}}\n\nexport type {prefix}Api = ReturnType<typeof create{prefix}Api>;\n"
    ));
    out
}

fn args_type(c: &Call) -> String {
    if c.args.is_empty() {
        return "Record<string, never>".to_owned();
    }
    let fields: Vec<String> = c
        .args
        .iter()
        .map(|a| format!("{}: {}", key(&a.name), render(&a.ty)))
        .collect();
    format!("{{ {} }}", fields.join("; "))
}

fn named(ty: &Ty, out: &mut BTreeSet<String>) {
    match ty {
        Ty::Named(name, _) => {
            out.insert(name.clone());
        }
        Ty::Array(inner) | Ty::Nullable(inner) | Ty::Record(inner) => named(inner, out),
        Ty::String | Ty::Number | Ty::Boolean | Ty::Unknown => {}
    }
}

fn comment(lines: &[String], indent: &str) -> String {
    let safe: Vec<String> = lines.iter().map(|l| l.replace("*/", "*\\/")).collect();
    match safe.as_slice() {
        [] => String::new(),
        [one] => format!("{indent}/** {one} */\n"),
        many => {
            let mut text = format!("{indent}/**\n");
            for line in many {
                if line.is_empty() {
                    text.push_str(&format!("{indent} *\n"));
                } else {
                    text.push_str(&format!("{indent} * {line}\n"));
                }
            }
            text.push_str(&format!("{indent} */\n"));
            text
        }
    }
}

/// A property name, quoted when it is not an identifier.
fn key(name: &str) -> String {
    if identifier(name) { name.to_owned() } else { quote(name) }
}

fn identifier(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

/// A TypeScript string literal.
pub fn quote(text: &str) -> String {
    format!(
        "'{}'",
        text.replace('\\', "\\\\").replace('\'', "\\'").replace('\n', "\\n")
    )
}
