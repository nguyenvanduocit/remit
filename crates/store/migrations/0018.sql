CREATE INDEX usage_home ON usage(home);
DROP INDEX drafts_chain;
CREATE INDEX drafts_home ON drafts(home, at);
DROP INDEX inbox_chain;
CREATE INDEX inbox_home ON inbox(home);
DROP INDEX session_inits_chain;
